# =--- Bibliotecas ---=
import math


# =--- Funções  ---=
def soma(numero1, numero2):
    resultado = numero1 + numero2
    return resultado

def subtracao(numero1, numero2):
    resultado = numero1 - numero2
    return resultado
    
def multiplicacao(numero1, numero2):
    resultado = numero1 * numero2
    return resultado

def divisao(numero1, numero2):
    resultado = numero1 / numero2
    return resultado

def raiz_quadrada(numero):
    resultado = math.sqrt(numero)
    return resultado


def exponenciacao(numero1, numero2):
    resultado = numero1 ** numero2
    return resultado


def raiz_cubica(numero):
    resultado = math.cbrt(numero)
    return resultado

def funcao_seno(numero):
    resultado = math.sin(numero)
    return resultado

def funcao_cosseno(numero):
    resultado = math.cos(numero)
    return resultado

def funcao_tangente(numero):
    resultado = math.tan(numero)
    return resultado
